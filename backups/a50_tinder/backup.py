"""A50: full backup of the old cards' tables before they are dropped.
For every table: schema.sql (columns, defaults, identity, constraints, indexes, RLS, policies,
grants), <table>.jsonl (every row as JSON, in primary-key order) and manifest.json (live row
count at the time of the backup, file row count, sha256). Exits non-zero when a count differs.
Run: python3 backup.py   (from anywhere; needs the Supabase CLI, see sb.py)"""
import hashlib, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sb import rows, scalar

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = {  # table -> primary key column
    'tinder_sentences': 'id',
    'tinder_word_distractors': 'media_id',
    'media_line_translations': 'id',
    'listening_questions': 'id',
}
PAGE = 5000

def ddl(t):
    cols = rows(f"""select a.attname as name, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull as notnull,
        pg_get_expr(d.adbin, d.adrelid) as def, a.attidentity as ident
      from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      where a.attrelid = 'public.{t}'::regclass and a.attnum > 0 and not a.attisdropped order by a.attnum""")
    lines = []
    for c in cols:
        s = f'  "{c["name"]}" {c["type"]}'
        if c['ident'] == 'a': s += ' generated always as identity'
        elif c['ident'] == 'd': s += ' generated by default as identity'
        if c['def'] is not None: s += f' default {c["def"]}'
        if c['notnull']: s += ' not null'
        lines.append(s)
    cons = rows(f"select conname, pg_get_constraintdef(oid) as def, contype from pg_constraint where conrelid = 'public.{t}'::regclass order by contype, conname")
    for c in cons:
        lines.append(f'  constraint "{c["conname"]}" {c["def"]}')
    out = [f'create table public.{t} (\n' + ',\n'.join(lines) + '\n);']
    conidx = {c['conname'] for c in cons}
    for i in rows(f"select indexname, indexdef from pg_indexes where schemaname='public' and tablename='{t}' order by indexname"):
        if i['indexname'] not in conidx:
            out.append(i['indexdef'] + ';')
    if scalar(f"select relrowsecurity from pg_class where oid = 'public.{t}'::regclass"):
        out.append(f'alter table public.{t} enable row level security;')
    for p in rows(f"select policyname, permissive, roles::text as roles, cmd, qual, with_check from pg_policies where schemaname='public' and tablename='{t}'"):
        roles = p['roles'].strip('{}') or 'public'
        s = f'create policy "{p["policyname"]}" on public.{t} as {p["permissive"].lower()} for {p["cmd"].lower()} to {roles}'
        if p['qual']: s += f' using ({p["qual"]})'
        if p['with_check']: s += f' with check ({p["with_check"]})'
        out.append(s + ';')
    for g in rows(f"select grantee, string_agg(privilege_type, ', ' order by privilege_type) as privs from information_schema.role_table_grants where table_schema='public' and table_name='{t}' and grantee in ('anon','authenticated','service_role') group by grantee order by grantee"):
        out.append(f'grant {g["privs"]} on public.{t} to {g["grantee"]};')
    return '\n'.join(out) + '\n'

def main():
    manifest = {'tables': {}}
    schema = ['-- A50 backup: the old cards\' tables (generated by backup.py)\n']
    ok = True
    for t, pk in TABLES.items():
        schema.append(f'-- {t}\n' + ddl(t))
        live = scalar(f'select count(*) from public.{t}')
        path = os.path.join(HERE, f'{t}.jsonl')
        n = 0
        h = hashlib.sha256()
        with open(path, 'w') as f:
            for off in range(0, live + PAGE, PAGE):
                page = rows(f'select to_jsonb(t) as r from (select * from public.{t} order by {pk} limit {PAGE} offset {off}) t')
                for r in page:
                    line = json.dumps(r['r'], ensure_ascii=False, sort_keys=True) + '\n'
                    f.write(line); h.update(line.encode()); n += 1
                if len(page) < PAGE: break
        live_after = scalar(f'select count(*) from public.{t}')
        manifest['tables'][t] = {'pk': pk, 'live_count': live, 'live_count_after': live_after, 'file_rows': n, 'sha256': h.hexdigest()}
        status = 'OK' if n == live == live_after else 'MISMATCH'
        ok &= status == 'OK'
        print(f'{t}: live {live}, file {n} -> {status}')
    with open(os.path.join(HERE, 'schema.sql'), 'w') as f:
        f.write('\n'.join(schema))
    with open(os.path.join(HERE, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=1)
    sys.exit(0 if ok else 1)

if __name__ == '__main__':
    main()
