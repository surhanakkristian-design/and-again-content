def adopt(dry=False):
    got, rejected, per = [], [], collections.Counter()
    for tag, src in ADOPT_SRCS:
        if not os.path.isdir(src):
            defect("%s sessions dir missing" % tag); continue
        for fn in sorted(os.listdir(src)):
            if not ADOPT_RE.match(fn) or fn[:-5] in ADOPTABLE:
                continue
            sid, sp = fn[:-5], os.path.join(src, fn)
            why, meta = adoption_check(sid, sp)
            if why:
                rejected.append("%s/%s: %s" % (tag, sid, why)); continue
