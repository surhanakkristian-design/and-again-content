# ================================================================ CLI envelope classifier (fix 1)
USAGE_RE = re.compile(r"usage limit|hit your (usage )?limit|weekly limit|5-hour limit|out of extra usage|"
                      r"credit balance is too low|limit will reset|limit resets|resets at \d|· resets|quota", re.I)
RATE_TYPES = {"rate_limit_error", "overloaded_error"}
AUTH_TYPES = {"authentication_error", "permission_error"}

def parse_envelope(stdout):
    s = (stdout or "").strip()
    if not s:
        return None
    try:
        j = json.loads(s)
        return j if isinstance(j, dict) else None
    except Exception:
        pass
    for l in reversed(s.splitlines()):
        try:
            j = json.loads(l)
        except Exception:
            continue
        if isinstance(j, dict):
            return j
    return None

def _int(v):
    if isinstance(v, bool): return None
    if isinstance(v, int): return v
    if isinstance(v, str) and v.strip().isdigit(): return int(v)
    return None

def _error_fields(j):
    """HTTP status FIELDS and API error TYPES of an envelope - never free text."""
    st, ty = set(), set()
    for k in ("api_error_status", "http_status", "status_code", "status"):
        v = _int(j.get(k))
        if v: st.add(v)
    err = j.get("error")
    if isinstance(err, dict):
        for e in (err, err.get("error") if isinstance(err.get("error"), dict) else {}):
            if isinstance(e.get("type"), str): ty.add(e["type"])
            for k in ("status", "status_code", "http_status"):
                v = _int(e.get(k))
                if v: st.add(v)
    elif isinstance(err, str) and err.endswith("_error"):
        ty.add(err)
    return st, ty

def classify(rc, stdout, stderr):
    """-> {"kind", "retry", "json", "message"}.  Decided ONLY from the envelope: exit code, is_error, type,
    HTTP status fields, API error types.  A '429' inside the result text or stderr is never looked at.
    A {"type":"result","is_error":false} envelope with exit 0 is SUCCESS, full stop."""
    j = parse_envelope(stdout)
    if j is not None and rc == 0 and not j.get("is_error") and j.get("type") == "result":
        return {"kind": "success", "retry": False, "json": j, "message": None}
    is_err = bool(j and j.get("is_error"))
    if j is not None and (is_err or rc != 0):
        st, ty = _error_fields(j)
        msg = ""
        if is_err and isinstance(j.get("result"), str):
            msg = j["result"]                                     # the error envelope's message
        e = j.get("error")
        if isinstance(e, dict):
            msg += " " + str(e.get("message") or (e.get("error") or {}).get("message") or "")
        if is_err and USAGE_RE.search(msg):
            return {"kind": "usage_limit", "retry": False, "json": j, "message": msg}
        if 429 in st or 529 in st or (ty & RATE_TYPES):
            return {"kind": "rate_limit", "retry": True, "json": j, "message": msg}
        if 401 in st or 403 in st or (ty & AUTH_TYPES):
            return {"kind": "auth", "retry": False, "json": j, "message": msg}
        if any(500 <= s < 600 for s in st):
            return {"kind": "server_error", "retry": True, "json": j, "message": msg}
        if rc != 0:
            return {"kind": "exit_nonzero", "retry": True, "json": j, "message": msg}
        return {"kind": "api_error", "retry": False, "json": j, "message": msg}
    if rc != 0:
        return {"kind": "exit_nonzero", "retry": True, "json": None, "message": ""}
    return {"kind": "unparsable", "retry": False, "json": j, "message": ""}

