def build_plan(only=None):
    plan = {"batches": [], "sessions_to_run": 0, "rows_to_pay": 0, "est_tokens": 0}
    for bid, rows, cname in batch_defs():
        if only and bid not in only:
            continue
        drv = get_drv(bid, rows)
        tasks = batch_tasks(bid, rows, cname, drv, rw_index())
        todo = [t for t in tasks if ann_complete(t[0], [r["n"] for r in t[3]]) is None]
        done = [t[0] for t in tasks if t not in todo]
        vrows = sum(len(t[3]) for t in todo if t[1] == "v")
        b = {"batch": bid, "rows": len(rows), "n_ranges": nranges([r["n"] for r in rows]),
             "sessions_complete_0_tokens": done,
             "rows_already_covered": len(rows) - vrows,
             "sessions_to_run": [{"session": t[0], "kind": t[1], "rows": len(t[3]), "est_tokens": est_for(t[1], len(t[3]))} for t in todo]}
        b["est_tokens"] = sum(x["est_tokens"] for x in b["sessions_to_run"])
        b["ref_est_1379_per_row"] = int(vrows * TOK_PER_ROW_ANN)
        plan["batches"].append(b)
        plan["sessions_to_run"] += len(todo); plan["rows_to_pay"] += vrows; plan["est_tokens"] += b["est_tokens"]
    plan["ref_est_1379_per_row"] = int(plan["rows_to_pay"] * TOK_PER_ROW_ANN)
    plan["means_tok_per_row"] = {k: (round(v, 1) if isinstance(v, float) else v) for k, v in MEANS.items()}
    return plan

def run_batch(bid, rows, cname, spawn):
    drv = get_drv(bid, rows)
    tasks = batch_tasks(bid, rows, cname, drv, rw_index())
    todo = [t for t in tasks if ann_complete(t[0], [r["n"] for r in t[3]]) is None]
    log("BATCH", bid, len(rows), "rows,", len(tasks), "sessions,", len(todo), "to run" if spawn else "missing (no spawn)")
    hs = None
    if spawn and todo:
        with cf.ThreadPoolExecutor(PAR) as ex:
            fs = {ex.submit(run_session, t[0], t[1], t[2], t[3], est_for(t[1], len(t[3])), ann_path_of(t[0]), "annotate"): t[0] for t in todo}
            for f in cf.as_completed(fs):
                try:
                    st, info = f.result()
                except HardStop as e:
                    hs = e; continue
                if st != "OK":
                    defect("session %s: %s %s" % (fs[f], st, info))
    # fix 3: assemble + write + commit BEFORE the gate is evaluated
    rwi = rw_index()
    MV = {}
    for cid, c in batch_chunks(bid, rows, cname):
        d = ann_complete(cid + "_v", [r["n"] for r in c])
        if d is not None:
            want = {r["n"] for r in c}
            for o in d["rows"]:
                if isinstance(o, dict) and o.get("n") in want:
                    MV[o["n"]] = o
    blocked = [r["n"] for r in rows if r["n"] not in MV or (is_fb(drv, r["n"]) and r["n"] not in rwi)]
    bset = set(blocked)
    anns = [assemble(r, drv[r["n"]], MV[r["n"]], rwi.get(r["n"]) if is_fb(drv, r["n"]) else None) for r in rows if r["n"] not in bset]
    ap = ann_file(bid)
    def _write(rows_out, gate):
        with open(ap, "w", encoding="utf-8") as fh:
            for a in rows_out:
                fh.write(json.dumps(a, ensure_ascii=False) + "\n")
        json.dump({"batch": bid, "phase": "2H", "rows_in_batch": len(rows), "rows_written": len(rows_out),
                   "rows_missing": len(blocked), "row_ranges_present": nranges([a["n"] for a in rows_out]),
                   "row_ranges_missing": nranges(blocked), "gate3": gate, "prompt_sha": ANN_PROMPT_SHA,
                   "written": time.strftime("%Y-%m-%dT%H:%M:%S")},
                  open(ap[:-6] + ".meta.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    if anns:
        _write(anns, "pending")
        commit("annotations %s: %d of %d rows written (before GATE 3)" % (bid, len(anns), len(rows)))
        g = gate_batch("annotate", bid, anns)
        if g["decision"] == "STOP":
            _write([dict(a, gate3="STOP") for a in anns], "STOP")
            commit("annotations %s marked gate3 STOP (excluded from upload only)" % bid)
        else:
            _write(anns, g["decision"])
            commit("annotations %s GATE 3 %s" % (bid, g["decision"]))
    else:
        log("EMPTY", bid, "no complete session; nothing written")
    if blocked:
        defect("batch %s: %d rows missing (%s)" % (bid, len(blocked), ",".join(nranges(blocked)[:8])))
    if hs:
        raise hs
    return len(anns)

