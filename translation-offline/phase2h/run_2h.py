def run_session(sid, kind, prompt, rows, est, path, stage):
    """One headless session with reservation, envelope-only retry, hard stops, ledger + projection after it.
    -> ("OK", rows) | ("FAIL"|"GIVEUP"|"SKIP"|"STOP"|"DRY", why)"""
    want = [r["n"] for r in rows]
    have = sess_complete(path, want)
    if have is not None:
        log("SKIP-DONE", sid, len(have["rows"]), "rows on disk, 0 tokens")
        return "OK", have["rows"]
    if CFG["dry"]:
        return "DRY", "dry run"
    with LOCK:
        gs = global_stop()
        if gs:
            log("NO-SPAWN", sid, "global stop:", gs)
            return "SKIP", gs
        if STATE["spent"] + STATE["inflight_est"] + est > CAP:
            STATE["stop"] = "token_cap"
            write_stop("STOP_token_cap.md", "Session `%s` (%s) refused: %d spent + %d reserved in flight + %d next > cap %d."
                       % (sid, stage, STATE["spent"], STATE["inflight_est"], est, CAP))
            tl("cap_refused", sid, spent=STATE["spent"], inflight_est=STATE["inflight_est"], est=est, cap=CAP)
            log("TOKEN-CAP", sid, STATE["spent"], STATE["inflight_est"], est, CAP)
            return "STOP", "token_cap"
        STATE["inflight_est"] += est
        STATE["launch"] += 1
        lidx = STATE["launch"]
        STATE["remaining"].pop(sid, None)
    tl("launch", sid, stage=stage, kind=kind, launch_index=lidx, rows=len(rows), n_range=nranges(want), est=est,
       reserved=STATE["spent"] + STATE["inflight_est"], cap=CAP)
    tok, t0, status, rc, so, se, env, attempt, envs = 0, time.time(), None, None, "", "", {"kind": None, "json": None}, 0, []
    try:
        for attempt in range(MAX_RETRY + 1):
            try:
                rc, so, se = spawn_claude(prompt, WALL_CAP_S)
            except subprocess.TimeoutExpired:
                status = "GIVEUP"; env = {"kind": "wall_timeout", "json": None}; envs.append("wall_timeout"); break
            except OSError as ex:
                rc, so, se = 127, "", "spawn failed: %s" % type(ex).__name__
            with LOCK:
                STATE["spawned"] += 1
            env = classify(rc, so, se)
            envs.append(env["kind"])
            tok += usage_total((env["json"] or {}).get("usage") or {})
            if env["kind"] == "success":
                status = "OK"; break
            tl("envelope_error", sid, attempt=attempt + 1, exit=rc, envelope=env["kind"], retry=env["retry"])
            if env["kind"] == "usage_limit":
                hard_stop("usage_limit", sid, env, rc, se)
            if lidx == 1 and attempt == 0 and env["kind"] != "rate_limit":
                hard_stop("first_session_failed", sid, env, rc, se)
            if env["retry"] and attempt < MAX_RETRY:
                d = backoff_s(attempt)
                log("RETRY", sid, "attempt", attempt + 1, "of", MAX_RETRY, "envelope", env["kind"], "exit", rc, "sleep %.0fs" % d)
                SLEEP(d)
                continue
            status = "GIVEUP"; break
        j = env.get("json") or {}
        txt = (j.get("result") or "") if status == "OK" else ""
        out = parse_rows(txt) if status == "OK" else None
        u = j.get("usage") or {}
        meta = {"session": sid, "stage": stage, "kind": kind, "exit": rc if rc is not None else -1,
                "envelope": env.get("kind"), "envelopes": envs, "attempts": attempt + 1,
                "wall_s": round(time.time() - t0, 1), "num_turns": j.get("num_turns"), "total_cost_usd": j.get("total_cost_usd"),
                "is_error": j.get("is_error"),
                **{k: u.get(k, 0) for k in ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")},
                "tokens": tok, "rows_asked": len(rows), "rows_returned": len(out or [])}
        if status == "OK" and out is None:
            meta["result_unparsable"] = txt[:300]
        if status != "OK":
            meta["stderr_tail"] = _redact(se)[-300:]
        json.dump({"meta": meta, "prompt": prompt, "result": txt, "rows": out if status == "OK" else None},
                  open(path, "w", encoding="utf-8"), ensure_ascii=False)
        with LOCK:
            STATE["sessions"][sid] = {"stage": stage, "kind": kind, "tokens": tok, "status": status if out is not None or status != "OK" else "UNPARSABLE",
                                      "envelopes": envs, "rows": len(out or []), "asked": len(rows),
                                      "ts": time.strftime("%Y-%m-%dT%H:%M:%S")}
        if status == "OK" and out is not None:
            return "OK", out
        return ("FAIL" if status == "OK" else "GIVEUP"), "%s after %d attempt(s)" % (env.get("kind"), attempt + 1)
    finally:
        with LOCK:
            STATE["inflight_est"] -= est
            STATE["spent"] += tok
            save_ledger()
            pj = projection()
        tl("end", sid, stage=stage, tokens=tok, envelopes=envs, wall_s=round(time.time() - t0, 1))
        log("LEDGER", sid, "tok", tok, "cum", pj["spent"], "projected_total", pj["projected_total"], "cap", CAP)
        _append(PROGRESS, {"ts": time.strftime("%Y-%m-%dT%H:%M:%S"), "who": "run_2h", "stage": stage, "session": sid,
                           "tokens": tok, "projection": pj})
        commit("%s session %s (%d tok, cum %d)" % (stage, sid, tok, pj["spent"]))

