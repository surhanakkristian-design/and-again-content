def _samp(rnd, pop, k): return rnd.sample(pop, min(k, len(pop)))          # fix 2: no recursion

def _binom_cdf(k, n, p):
    if k < 0: return 0.0
    if k >= n: return 1.0
    if p <= 0.0: return 1.0
    if p >= 1.0: return 0.0
    lp, lq = math.log(p), math.log1p(-p)
    return min(1.0, sum(math.exp(math.lgamma(n + 1) - math.lgamma(i + 1) - math.lgamma(n - i + 1) + i * lp + (n - i) * lq)
                        for i in range(k + 1)))

def cp(k, n, alpha=0.05):
    """Exact two-sided Clopper-Pearson interval in PERCENT (2 decimals)."""
    if not n:
        return (None, None)
    def bis(f, lo=0.0, hi=1.0):
        for _ in range(200):
            m = (lo + hi) / 2
            if f(m): hi = m
            else: lo = m
        return (lo + hi) / 2
    lo = 0.0 if k == 0 else bis(lambda p: 1.0 - _binom_cdf(k - 1, n, p) >= alpha / 2)
    hi = 1.0 if k == n else bis(lambda p: _binom_cdf(k, n, p) <= alpha / 2)
    return (round(100 * lo, 2), round(100 * hi, 2))

def gate_counts(pick):
    """2G gate3() counting, unchanged (AG v4, reader_nom, g4 diagnostic)."""
    c = {k: collections.Counter() for k in ("agv4", "reader_nom", "g4_diag")}
    for a in pick:
        vp = a.get("script_voice_paths") or {}
        mvoice = (a.get("voice") or "").strip().lower() or None
        reads_pass = bool(vp.get("agv4_main_passive") or vp.get("agv4_main_reflex"))
        if mvoice is None: c["agv4"]["UNDECIDED"] += 1
        elif mvoice in ("active_agent", "active_prodrop") and reads_pass: c["agv4"]["ERROR"] += 1
        elif mvoice == "passive" and not reads_pass: c["agv4"]["ERROR"] += 1
        else: c["agv4"]["AGREE"] += 1
        g4p = bool(vp.get("g4_v3_passive_or_reflex") or vp.get("g4_v2_sk_reflex") or vp.get("g4_cz_se_missed"))
        if mvoice is None: c["g4_diag"]["UNDECIDED"] += 1
        elif (mvoice in ("active_agent", "active_prodrop") and g4p) or (mvoice == "passive" and not g4p): c["g4_diag"]["ERROR"] += 1
        else: c["g4_diag"]["AGREE"] += 1
        ag = a.get("script_reader_agent")
        gm = words(a.get("subject")); ga = set(gm)
        for e in (a.get("embedded_agents") or []): ga |= words(e)
        if not ag: c["reader_nom"]["CONSERVATIVE" if gm else "AGREE"] += 1
        elif not ga: c["reader_nom"]["ERROR"] += 1
        else: c["reader_nom"]["AGREE" if (words(ag) & gm) else "ERROR"] += 1
    return c

def gate_decide(k, n, bar=GATE3_BAR, min_decided=GATE3_MIN_DECIDED):
    """ERROR-of-decided k/n.  n < 40 -> FLAG only; CP lower > bar -> STOP (that batch only);
    point > bar -> FLAG; else PASS."""
    point = round(100.0 * k / n, 2) if n else None
    lo, hi = cp(k, n)
    if not n:
        dec, why = "FLAG", "0 decided rows"
    elif n < min_decided:
        dec, why = "FLAG", "decided %d < %d: FLAG only, never STOP" % (n, min_decided)
    elif lo > bar:
        dec, why = "STOP", "CP95 lower bound %.2f %% > %.1f %% bar" % (lo, bar)
    elif point > bar:
        dec, why = "FLAG", "point %.2f %% > %.1f %% bar, CP95 lower %.2f %% not above it" % (point, bar, lo)
    else:
        dec, why = "PASS", "point %.2f %% <= %.1f %% bar" % (point, bar)
    return {"errors": k, "decided": n, "point_pct": point, "cp95_pct": [lo, hi], "decision": dec, "why": why, "bar": bar}

def gate_batch(stage, bid, anns, n_pick=GATE3_N_ANN, seed=None):
    rnd = random.Random(seed if seed is not None else int(hashlib.sha256(bid.encode()).hexdigest()[:12], 16))
    pick = _samp(rnd, anns, n_pick)
    c = GATE_COUNTS_HOOK(bid, pick) if GATE_COUNTS_HOOK else gate_counts(pick)
    g = {"stage": stage, "batch": bid, "n_scored": len(pick), "rows_in_scope": len(anns), "ts": time.strftime("%Y-%m-%dT%H:%M:%S")}
    for m in ("agv4", "reader_nom"):
        g[m] = dict(gate_decide(c[m]["ERROR"], c[m]["AGREE"] + c[m]["ERROR"]), counts=dict(c[m]))
    gd = c["g4_diag"]
    g["g4_RECORDED_ONLY"] = {"counts": dict(gd), "ERROR_of_decided_pct": round(100.0 * gd["ERROR"] / (gd["AGREE"] + gd["ERROR"]), 2)
                             if (gd["AGREE"] + gd["ERROR"]) else None, "note": "recorded only, never gates"}
    decs = [g[m]["decision"] for m in ("agv4", "reader_nom")]
    g["decision"] = "STOP" if "STOP" in decs else ("FLAG" if "FLAG" in decs else "PASS")
    for m in ("agv4", "reader_nom"):
        d = g[m]["decision"]
        if d in ("FLAG", "STOP"):
            fn = "%s_gate3_%s_%s.md" % (d, m, bid)
            with open(os.path.join(CFG["hd"], fn), "w", encoding="utf-8") as fh:
                fh.write("# Phase 2H GATE 3 %s: %s, batch %s (%s stage)\n\n%s\n\nERROR %d of %d decided, point %s %%, exact CP95 %s %%, "
                         "bar %.1f %%.\nCounts: %s\ng4 (recorded only): %s\n\n%s\n" % (
                             d, m, bid, stage, g[m]["why"], g[m]["errors"], g[m]["decided"], g[m]["point_pct"], g[m]["cp95_pct"],
                             GATE3_BAR, g[m]["counts"], g["g4_RECORDED_ONLY"],
                             "This batch is excluded from the upload xlsx; its rows are still written (gate3: STOP). "
                             "Every other batch and every other stage continues." if d == "STOP" else
                             "FLAG only: nothing is stopped or excluded."))
    with LOCK:
        allg = json.load(open(GATES, encoding="utf-8")) if os.path.exists(GATES) else {"bar_pct": GATE3_BAR}
        allg.setdefault(stage, {})[bid] = g
        json.dump(allg, open(GATES, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    log("GATE3", stage, bid, g["decision"], json.dumps({m: [g[m]["errors"], g[m]["decided"], g[m]["cp95_pct"], g[m]["decision"]]
                                                          for m in ("agv4", "reader_nom")}))
    commit("GATE 3 %s %s: %s" % (stage, bid, g["decision"]))
    return g

