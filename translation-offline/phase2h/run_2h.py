def write_xlsx(path, sheet, header, rows):
    def row_xml(vals, ri):
        return '<row r="%d">%s</row>' % (ri, "".join('<c r="%s%d" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>'
                                                     % (colname(i), ri, xesc(v)) for i, v in enumerate(vals)))
    body = row_xml(header, 1) + "".join(row_xml(r, i) for i, r in enumerate(rows, 2))
    ns = "http://schemas.openxmlformats.org"
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="%s/package/2006/content-types">'
                   '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                   '<Default Extension="xml" ContentType="application/xml"/>'
                   '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
                   '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>' % ns)
        z.writestr("_rels/.rels", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="%s/package/2006/relationships">'
                   '<Relationship Id="rId1" Type="%s/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>' % (ns, ns))
        z.writestr("xl/workbook.xml", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="%s/spreadsheetml/2006/main" '
                   'xmlns:r="%s/officeDocument/2006/relationships"><sheets><sheet name="%s" sheetId="1" r:id="rId1"/></sheets></workbook>' % (ns, ns, sheet))
        z.writestr("xl/_rels/workbook.xml.rels", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="%s/package/2006/relationships">'
                   '<Relationship Id="rId1" Type="%s/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/></Relationships>' % (ns, ns))
        z.writestr("xl/worksheets/sheet1.xml", '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="%s/spreadsheetml/2006/main">'
                   '<sheetData>%s</sheetData></worksheet>' % (ns, body))

def upload():
    anns = load_jsonl(os.path.join(OUT, "annotations_cz_final.jsonl"))
    keep = [a for a in anns if a.get("gate3") != "STOP"]
    excl = [a["n"] for a in anns if a.get("gate3") == "STOP"]
    rows, big, big_id = [], 0, None
    for a in keep:
        sj = json.dumps(a, ensure_ascii=False)
        if len(sj) > big: big, big_id = len(sj), a.get("exercise_id")
        rows.append([a.get("exercise_id"), a.get("language_code"), a.get("level"), a.get("src"), a.get("en"), sj])
    xp = os.path.join(OUT, "upload_cz_final.xlsx")
    write_xlsx(xp, "cz", COLS, rows)
    mrep = json.load(open(os.path.join(CFG["hd"], "merge_2h.json"), encoding="utf-8")) if os.path.exists(os.path.join(CFG["hd"], "merge_2h.json")) else {}
    basetxt = open(os.path.join(F2, "out", "UPLOAD_README.md"), encoding="utf-8").read()
    demoted = "\n".join(("##" + l) if l.startswith("#") else l for l in basetxt.splitlines())
    rd = ("# Phase 2H upload package - Czech (`out/upload_cz_final.xlsx`)\n\n"
          "Sheet **`cz`**, **%d rows**, columns %s; the whole annotation as JSON in `structure_json`. Nothing was uploaded, "
          "nothing was written to the database.\n\n"
          "* Rows in `out/annotations_cz_final.jsonl`: %d; sources: %s.\n"
          "* Excluded from the xlsx (GATE 3 STOP batches, rows marked `gate3: \"STOP\"` in the jsonl): %d rows (%s).\n"
          "* Rows still missing of 4,064: %s.\n"
          "* Largest `structure_json` cell: %d chars (Excel limit 32,767), exercise_id %s.\n"
          "* `lk`, `lk_verdict`, `lk_reason` of every row judged in 2H come from the dedicated lk pass "
          "(prompt sha16 `%s`, acceptance rule in `lk_sessions_2h.json`).\n\n---\n\n"
          "## Carried over from the Phase 2F README (headings demoted; the Czech counts above supersede it)\n\n%s\n"
          % (len(rows), ", ".join("`%s`" % c for c in COLS), len(anns), json.dumps(mrep.get("sources", {})), len(excl),
             ", ".join(nranges(excl)[:12]) or "-", json.dumps(mrep.get("rows_missing_of_4064", {})), big, big_id,
             LK_PROMPT_SHA, demoted))
    open(os.path.join(CFG["hd"], "UPLOAD_README.md"), "w", encoding="utf-8").write(rd)
    log("UPLOAD", len(rows), "rows,", len(excl), "excluded")
    commit("upload_cz_final.xlsx %d rows + UPLOAD_README (Phase 2H)" % len(rows))
    return {"rows": len(rows), "excluded": len(excl), "largest": big}

# ================================================================ CLI
def main(argv):
    if not argv or argv[0] not in ("annotate", "lk", "merge", "upload"):
        sys.stderr.write(__doc__); return 2
    cmd, dry = argv[0], "--dry" in argv
    cap = int(argv[argv.index("--cap") + 1]) if "--cap" in argv else DEFAULT_CAP
    configure(SCRIPT_DIR, commit=not dry, dry=dry)
    try:
        if cmd == "annotate":
            annotate(cap, dry=dry, no_spawn="--no-spawn" in argv)
        elif cmd == "lk":
            lk_stage(cap, dry=dry)
        elif cmd == "merge":
            merge()
        else:
            upload()
    except HardStop as e:
        log("EXIT hard stop", e)
        save_ledger(); commit("HARD STOP %s" % e)
        return 4
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
