def lemmas(t):
    c = [t]
    for suf, rep in (("ies", "y"), ("ied", "y"), ("ier", "y"), ("iest", "y"), ("ing", ""), ("ing", "e"), ("ed", ""), ("ed", "e"),
                     ("es", ""), ("s", ""), ("er", ""), ("est", ""), ("ly", "")):
        if t.endswith(suf) and len(t) - len(suf) >= 3:
            b = t[: -len(suf)] + rep; c.append(b)
            if len(b) > 3 and b[-1] == b[-2] and not rep: c.append(b[:-1])
    return list(dict.fromkeys(c))

