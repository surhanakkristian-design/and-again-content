def lk_row(n):
    r = BYN[n]
    return {"n": n, "en": r["en"], "lk_supplied": r.get("correct_answer_en")}

def lk_sessions():
    ns = lk_targets()
    return [("lk2h_s%02d" % (i // NSESS + 1), [lk_row(n) for n in ns[i:i + NSESS]]) for i in range(0, len(ns), NSESS)]

def lk_prompt(rows):
    return LK_2D + "\n".join(line({"n": r["n"], "en": r["en"], "correct_answer_en": r["lk_supplied"]}) for r in rows)

def nonexact(out, want):
    rs = [o for o in out if isinstance(o, dict) and o.get("n") in want]
    return sum(1 for o in rs if o.get("class") in ("adjust", "unusable")), len(rs)

def majority(outs, want):
    """Per-row majority class over three runs; a tie goes to the most conservative verdict
    (unusable > adjust > exact); the row object is taken from the latest run carrying that class."""
    res = []
    for n in sorted(want):
        cands = [o for out in outs for o in out if isinstance(o, dict) and o.get("n") == n]
        if not cands:
            continue
        cnt = collections.Counter(o.get("class") for o in cands)
        top = max(cnt.values())
        cls = max([c for c, v in cnt.items() if v == top], key=lambda c: LK_ORDER.get(c, 0))
        res.append(dict([o for o in cands if o.get("class") == cls][-1], majority_votes=dict(cnt)))
    return res

def lk_session_accept(sid, rows):
    want = {r["n"] for r in rows}
    prompt = lk_prompt(rows)
    est = est_for("lk", len(rows))
    rec = {"session": sid, "rows": len(rows), "n_range": nranges(want), "runs": [], "status": None, "used": None}
    outs = {}
    def run(k):
        rid = "%s_r%d" % (sid, k)
        st, out = run_session(rid, "lk", prompt, rows, est, os.path.join(LKSESS, rid + ".json"), "lk")
        if st != "OK":
            rec["runs"].append({"attempt": k, "status": st, "why": out if isinstance(out, str) else None})
            return None
        kk, nn = nonexact(out, want)
        rec["runs"].append({"attempt": k, "status": "OK", "nonexact": kk, "rows_returned": nn,
                            "nonexact_pct": round(100.0 * kk / nn, 2) if nn else None, "cp95_pct": list(cp(kk, nn)),
                            "file": os.path.relpath(os.path.join(LKSESS, rid + ".json"), CFG["hd"])})
        outs[k] = out
        return 100.0 * kk / nn if nn else 0.0
    r1 = run(1)
    if r1 is None:
        rec["status"] = "FAILED"; return rec, None
    if r1 >= LK_ACCEPT_PCT:
        rec.update(status="accepted", used="r1"); return rec, outs[1]
    r2 = run(2)
    if r2 is None:
        rec.update(status="accepted_below_bar_run2_failed", used="r1"); return rec, outs[1]
    rec["diff_pts"] = round(abs(r1 - r2), 2)
    if abs(r1 - r2) > LK_RUN_DIFF_PTS:
        r3 = run(3)
        if r3 is None:
            rec.update(status="run3_failed_kept_run2", used="r2"); return rec, outs[2]
        rec.update(status="majority_of_3", used="majority"); return rec, majority([outs[1], outs[2], outs[3]], want)
    if r2 >= LK_ACCEPT_PCT:
        rec.update(status="accepted", used="r2"); return rec, outs[2]
    rec.update(status="accepted_below_bar", used="r2"); return rec, outs[2]

def apply_lk(row, o):
    """The dedicated lk judgement replaces lk[0], lk_verdict and lk_reason; nothing else changes."""
    a = dict(row)
    cls = o.get("class")
    en = a.get("en") or ""
    lk = list(a.get("lk") or [])
    if cls == "exact":
        new = a.get("lk_supplied")
    elif cls == "adjust":
        new = o.get("lk") or o.get("lk_fixed")
    else:
        new = o.get("lk_fixed")
    applied = bool(new and new in en)
    if applied:
        lk = [new] + lk[1:] if lk else [new]
    a["lk"] = lk
    # 2G verdict mapping (test T10 reproduces 2G's merged rows): an "unusable" judgement whose lk_fixed is a verbatim
    # span of en was applied and is recorded as "adjusted"; only an unusable row without a usable fix stays "unusable".
    a["lk_verdict"] = "exact" if cls == "exact" else ("adjusted" if (cls == "adjust" or applied) else "unusable")
    a["lk_reason"] = o.get("reason")
    return a

